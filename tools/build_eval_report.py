#!/usr/bin/env python3
"""Write evals/skillevaluator/REPORT.md from the SkillEvaluator summaries.

Reads the summary.json files produced by tools/run_skillevaluator.py:
    evals/skillevaluator/quality-check/   static quality score
    evals/skillevaluator/static/tier1/    Tier 1 gate without LLM checks
    evals/skillevaluator/tier1/           Tier 1 gate with LLM security and rubric
    evals/skillevaluator/rubric-eval/     LLM rubric alone
    evals/skillevaluator/baseline.json    quality scores before the rewrite (optional)

Usage:
    python tools/build_eval_report.py
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVALS = ROOT / "evals" / "skillevaluator"


def load(*parts: str) -> dict[str, dict]:
    path = EVALS.joinpath(*parts)
    if not path.is_file():
        return {}
    return {row["skill"]: row for row in json.loads(path.read_text(encoding="utf-8"))}


def mean(values: list[float]) -> float:
    return sum(values) / len(values) if values else float("nan")


def main() -> int:
    quality = load("quality-check", "summary.json")
    static = load("static", "tier1", "summary.json")
    full = load("tier1", "summary.json")
    rubric_only = load("rubric-eval", "summary.json")
    baseline_path = EVALS / "baseline.json"
    baseline = json.loads(baseline_path.read_text(encoding="utf-8")) if baseline_path.is_file() else {}
    skills = sorted(p.name for p in (ROOT / "skills").iterdir() if (p / "SKILL.md").is_file())
    if not quality or not static:
        print("error: run tools/run_skillevaluator.py for quality-check and static tier1 first", file=sys.stderr)
        return 1

    def rubric(skill: str) -> tuple[float | None, dict]:
        for source in (full, rubric_only):
            row = source.get(skill) or {}
            if row.get("rubric_score") is not None:
                return row["rubric_score"], row.get("rubric_criteria", {})
        return None, {}

    rubric_scores = {s: rubric(s) for s in skills}
    judged = [v[0] for v in rubric_scores.values() if v[0] is not None]
    q_now = [quality[s]["quality_score"] for s in skills if s in quality]
    q_before = [baseline[s] for s in skills if s in baseline]
    static_status = Counter(static[s]["status"] for s in skills if s in static)
    full_status = Counter(full[s]["status"] for s in skills if s in full)
    static_sev = Counter()
    for s in skills:
        static_sev.update({k: v for k, v in (static.get(s, {}).get("severity") or {}).items() if v})
    full_high = [(s, f) for s in skills for f in full.get(s, {}).get("findings", []) if f.get("severity") in ("high", "critical")]
    incomplete = Counter(scan for s in skills for scan in full.get(s, {}).get("incomplete_scans", []))
    criteria: dict[str, list[float]] = {}
    for _, per in rubric_scores.values():
        for cid, score in per.items():
            criteria.setdefault(cid, []).append(score)

    out = ["# SkillEvaluator results", "",
           "Generated by `tools/build_eval_report.py` from the summaries in this folder. "
           "Tool: NVIDIA SkillEvaluator 0.5.0 (https://docs.nvidia.com/skills/skillevaluator).", "",
           "## Summary", "",
           "| Check | Result |", "|---|---|",
           f"| Skills evaluated | {len(skills)} |"]
    if q_before:
        out.append(f"| Static quality score before the rewrite | mean {mean(q_before):.1f}, min {min(q_before):.1f}, max {max(q_before):.1f} |")
    out += [f"| Static quality score now | mean {mean(q_now):.1f}, min {min(q_now):.1f}, max {max(q_now):.1f} |",
            f"| Tier 1 gate, static checks (no LLM) | " + ", ".join(f"{n} {s}" for s, n in static_status.most_common()) + " |",
            f"| Tier 1 static findings | " + (", ".join(f"{static_sev[k]} {k}" for k in ("critical", "high", "medium", "low") if static_sev[k]) or "none") + " |",
            f"| LLM rubric (judge model in the run notes) | {len(judged)} of {len(skills)} skills judged; mean {mean(judged):.1f}, "
            f"min {min(judged):.1f}, max {max(judged):.1f}; pass mark 70 |" if judged else "| LLM rubric | not run |",
            f"| Tier 1 gate with LLM security and rubric | " + (", ".join(f"{n} {s}" for s, n in full_status.most_common()) or "not run") + " |",
            f"| Tier 3 eval datasets | {len(skills)} files, {3 * len(skills)} cases, schema-validated; live run not performed |", ""]

    out += ["## Per skill", "",
            "| Skill | Quality before | Quality now | LLM rubric | Tier 1 static | Tier 1 with LLM | Incomplete LLM scans |",
            "|---|---|---|---|---|---|---|"]
    for s in skills:
        score = rubric_scores[s][0]
        out.append(f"| {s} | {baseline.get(s, 'n/a')} | {quality.get(s, {}).get('quality_score', 'n/a')} | "
                   f"{score if score is not None else 'not judged'} | {static.get(s, {}).get('status', 'n/a')} | "
                   f"{full.get(s, {}).get('status', 'not run')} | {', '.join(full.get(s, {}).get('incomplete_scans', []))} |")

    if criteria:
        out += ["", "## LLM rubric by criterion (0 to 10; 7 passes)", "", "| Criterion | Mean | Min | Skills below 7 |", "|---|---|---|---|"]
        out += [f"| {cid} | {mean(v):.1f} | {min(v)} | {sum(1 for x in v if x < 7)} |" for cid, v in criteria.items()]

    out += ["", "## Tier 1 static findings by type", "", "| Skills | Severity | Finding |", "|---|---|---|"]
    kinds = Counter()
    for s in skills:
        for key in {(f["severity"], f["validator"], str(f["check"])[:70]) for f in static.get(s, {}).get("findings", [])}:
            kinds[key] += 1
    out += [f"| {n} | {sev} | {validator}: {check} |" for (sev, validator, check), n in kinds.most_common()] or ["| 0 | | none |"]

    out += ["", "## High-severity findings from the LLM security pass", ""]
    if full_high:
        out += ["| Skill | Finding |", "|---|---|"]
        out += [f"| {s} | {str(f['check'])[:60]}: {str(f['message'])[:260].replace('|', '/')} |" for s, f in full_high]
    else:
        out.append("None in the latest results.")
    if incomplete:
        out += ["", "LLM scans that did not complete: " + ", ".join(f"{scan} ({n} skills)" for scan, n in incomplete.most_common()) + "."]

    notes = EVALS / "NOTES.md"
    if notes.is_file():  # hand-written context for the numbers above
        out += ["", notes.read_text(encoding="utf-8").rstrip()]

    (EVALS / "REPORT.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {EVALS / 'REPORT.md'}: {len(skills)} skills, {len(judged)} judged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
