#!/usr/bin/env python3
"""Give each skill a copy of shared/scholarly_api.py trimmed to the functions it calls.

Skills must work when copied on their own, so each one carries its own client as
scripts/_scholarly_api.py. To keep every skill to the least code and network reach it
needs, the copy contains only the names its scripts use (`api.<name>`) and whatever
those depend on. Edit shared/scholarly_api.py, then run this script.

    python tools/sync_shared.py            # rewrite the copies
    python tools/sync_shared.py --check    # fail if any copy is out of date
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ROOT / "shared" / "scholarly_api.py"
COPY_NAME = "_scholarly_api.py"
USE_RE = re.compile(r"\bapi\.([A-Za-z_][A-Za-z0-9_]*)")


def top_level(tree: ast.Module) -> tuple[dict[str, ast.stmt], list[ast.stmt]]:
    """Map each top-level name to the statement defining it, and list the import statements."""
    defined: dict[str, ast.stmt] = {}
    imports: list[ast.stmt] = []
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            imports.append(node)
        elif isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            defined[node.name] = node
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for target in targets:
                if isinstance(target, ast.Name):
                    defined[target.id] = node
    return defined, imports


def names_in(node: ast.AST) -> set[str]:
    return {n.id for n in ast.walk(node) if isinstance(n, ast.Name)} | \
           {n.value.id for n in ast.walk(node) if isinstance(n, ast.Attribute) and isinstance(n.value, ast.Name)}


def trim(source: str, roots: set[str]) -> str:
    """Return the module reduced to `roots` and everything they reference."""
    tree = ast.parse(source)
    defined, imports = top_level(tree)
    unknown = roots - set(defined)
    if unknown:
        raise ValueError(f"names not defined in the shared client: {sorted(unknown)}")
    keep: set[str] = set()
    queue = list(roots)
    while queue:
        name = queue.pop()
        if name in keep:
            continue
        keep.add(name)
        queue.extend(n for n in names_in(defined[name]) if n in defined and n not in keep)

    lines = source.splitlines()
    kept_nodes = sorted({id(defined[n]): defined[n] for n in keep}.values(), key=lambda n: n.lineno)
    used = set().union(*(names_in(n) for n in kept_nodes)) if kept_nodes else set()

    def text(node: ast.stmt) -> str:
        return "\n".join(lines[node.lineno - 1:node.end_lineno])

    kept_imports = []
    for node in imports:
        if isinstance(node, ast.ImportFrom) and node.module == "__future__":
            kept_imports.append(text(node))
            continue
        bound = {(a.asname or a.name).split(".")[0] for a in node.names}
        if bound & used:
            kept_imports.append(text(node))
    header = ('#!/usr/bin/env python3\n"""Scholarly API helpers used by this skill.\n\n'
              "Generated by tools/sync_shared.py from shared/scholarly_api.py and trimmed to the functions\n"
              'this skill calls. Do not edit this copy; edit the shared file and run the sync tool.\n"""\n')
    blocks = []
    for node in kept_nodes:
        gap = "\n\n\n" if isinstance(node, (ast.FunctionDef, ast.ClassDef)) else "\n"
        blocks.append(gap + text(node))
    future = [i for i in kept_imports if "__future__" in i]
    others = [i for i in kept_imports if "__future__" not in i]
    body = "".join(blocks).strip("\n")
    return header + "\n" + "\n".join(future) + ("\n\n" if future else "") + "\n".join(others) + "\n\n" + body + "\n"


def consumers() -> dict[Path, set[str]]:
    """Each skill whose scripts import the client, with the client names they use."""
    found: dict[Path, set[str]] = {}
    for scripts in sorted((ROOT / "skills").glob("*/scripts")):
        roots: set[str] = set()
        for script in scripts.glob("[!_]*.py"):
            code = script.read_text(encoding="utf-8")
            if "import _scholarly_api as api" in code:
                roots |= set(USE_RE.findall(code))
        if roots:
            found[scripts] = roots
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify the copies are current; write nothing")
    args = parser.parse_args()
    source = SHARED.read_text(encoding="utf-8")
    stale = []
    for scripts, roots in consumers().items():
        try:
            trimmed = trim(source, roots)
        except ValueError as exc:
            print(f"error: {scripts.parent.name}: {exc}", file=sys.stderr)
            return 1
        compile(trimmed, str(scripts / COPY_NAME), "exec")  # a trimmed copy must still be valid Python
        target = scripts / COPY_NAME
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != trimmed:
                stale.append(scripts.parent.name)
        else:
            target.write_text(trimmed, encoding="utf-8", newline="\n")
            print(f"synced {scripts.parent.name}: {len(trimmed.splitlines())} lines, {len(roots)} entry points")
    if stale:
        print(f"error: out-of-date copies in: {', '.join(stale)} (run python tools/sync_shared.py)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
